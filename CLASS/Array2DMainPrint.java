public class Array2DMainPrint
{
    public static void main(String [] args )
    {

        // 1. Initialize a 2D array with with values
        int[][] arr = {
            {10, 20, 30},
            {40, 90, 60},
            {70, 80,90},
        };

        // 2.Display a specific value 
        for (int i =0; i<arr[i].length;i++){
            for (int j =0; j<arr[i].length;j++)
                {
            System.out.print(arr[i][j]+"\t");
        }
        System.out.println();
        }


        System.out.println();
    } 
}   
